from datetime import datetime
import os


REPORT_FOLDER = "../reports"

os.makedirs(REPORT_FOLDER, exist_ok=True)


def generate_forensic_report(
    evidence_list,
    custody_events,
    audit_logs,
    correlation_timeline
):

    timestamp = datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S"
    )

    filename = (
        f"SecureX_Forensic_Report_"
        f"{datetime.now().strftime('%Y%m%d_%H%M%S')}.txt"
    )

    report_path = os.path.join(
        REPORT_FOLDER,
        filename
    )

    with open(
        report_path,
        "w",
        encoding="utf-8"
    ) as report:

        report.write("=" * 70 + "\n")
        report.write("SECUREX FORENSIC INVESTIGATION REPORT\n")
        report.write("=" * 70 + "\n\n")

        report.write(
            f"Generated: {timestamp}\n"
        )

        report.write(
            "Platform: SecureX - Unified Digital Evidence Platform\n\n"
        )

        # ----------------------------------------------------
        # EVIDENCE SUMMARY
        # ----------------------------------------------------

        report.write("=" * 70 + "\n")
        report.write("1. EVIDENCE SUMMARY\n")
        report.write("=" * 70 + "\n\n")

        report.write(
            f"Total Evidence Items: {len(evidence_list)}\n\n"
        )

        for evidence in evidence_list:

            report.write(
                f"Evidence ID : {evidence.evidence_id}\n"
            )

            report.write(
                f"Filename    : {evidence.filename}\n"
            )

            report.write(
                f"SHA-256     : {evidence.sha256_hash}\n"
            )

            report.write(
                f"Status      : {evidence.status}\n"
            )

            report.write(
                f"Uploaded By : {evidence.uploaded_by}\n"
            )

            report.write(
                f"Uploaded At : {evidence.uploaded_at}\n"
            )

            report.write("-" * 50 + "\n")

        # ----------------------------------------------------
        # CHAIN OF CUSTODY
        # ----------------------------------------------------

        report.write("\n")
        report.write("=" * 70 + "\n")
        report.write("2. CHAIN OF CUSTODY\n")
        report.write("=" * 70 + "\n\n")

        for event in custody_events:

            report.write(
                f"{event.timestamp} | "
                f"{event.from_user} -> {event.to_user}\n"
            )

            report.write(
                f"Action: {event.action}\n"
            )

            report.write(
                f"Notes : {event.notes}\n\n"
            )

        # ----------------------------------------------------
        # AUDIT LOG
        # ----------------------------------------------------

        report.write("=" * 70 + "\n")
        report.write("3. AUDIT LOG\n")
        report.write("=" * 70 + "\n\n")

        for log in audit_logs:

            report.write(
                f"{log.timestamp} | "
                f"{log.user} | "
                f"{log.action}\n"
            )

            report.write(
                f"Details: {log.details}\n\n"
            )

        # ----------------------------------------------------
        # CORRELATION TIMELINE
        # ----------------------------------------------------

        report.write("=" * 70 + "\n")
        report.write("4. CROSS-EVIDENCE CORRELATION TIMELINE\n")
        report.write("=" * 70 + "\n\n")

        for event in correlation_timeline:

            report.write(
                f"{event['timestamp']} | "
                f"{event['evidence_id']} | "
                f"{event['filename']} | "
                f"{event['event']}\n"
            )

        # ----------------------------------------------------
        # CONCLUSION
        # ----------------------------------------------------

        report.write("\n")
        report.write("=" * 70 + "\n")
        report.write("5. SYSTEM CONCLUSION\n")
        report.write("=" * 70 + "\n\n")

        report.write(
            "SecureX completed evidence collection, "
            "SHA-256 integrity verification, chain-of-custody "
            "tracking, audit logging and cross-evidence "
            "timeline correlation.\n\n"
        )

        report.write(
            "NOTE: This report is generated by a prototype "
            "digital evidence management system. SHA-256 "
            "verification demonstrates file integrity relative "
            "to the stored reference hash but does not by itself "
            "establish legal admissibility or complete forensic "
            "authenticity.\n"
        )

    return report_path, filename